// ABI generation from Foundry's out/ (spec 05: ABIs generated at build time, never hand-written).
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const CONTRACTS = [
  'MandateHook', 'PasskeyValidator', 'AgentKeyValidator', 'StandingOrders', 'PayoutRail', 'PriceOracle', 'TreasuryDesk',
  'PraetorToken', 'IdentityRegistry', 'Compliance', 'RefusalLog', 'Anchor', 'PraetorPaymaster', 'WeCrossInbox', 'NoOwner',
  'TestDollar',
] as const;
export type ContractName = (typeof CONTRACTS)[number];

// The hook's external libraries revert with their own errors: merge them so callers can decode every refusal.
const HOOK_LIBRARIES = ['ConsortiumLib', 'OwnerLib', 'DecisionLib', 'PostCheckLib'];

type AbiItem = { type: string; name?: string; inputs?: { type: string }[] };

function read(outDir: string, name: string): AbiItem[] {
  return JSON.parse(readFileSync(resolve(outDir, `${name}.sol`, `${name}.json`), 'utf8')).abi as AbiItem[];
}

const sig = (x: AbiItem) => `${x.type}:${x.name}(${(x.inputs ?? []).map((i) => i.type).join(',')})`;

export function buildAbisSource(outDir: string): string {
  const parts = ['// Generated by packages/chain/scripts/gen-abis.ts from contracts/base/out. Do not edit by hand.', ''];
  for (const name of CONTRACTS) {
    let abi = read(outDir, name);
    if (name === 'MandateHook') {
      const seen = new Set(abi.map(sig));
      for (const lib of HOOK_LIBRARIES) {
        for (const item of read(outDir, lib)) {
          if (item.type === 'error' && !seen.has(sig(item))) {
            seen.add(sig(item));
            abi = [...abi, item];
          }
        }
      }
    }
    parts.push(`export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;`, '');
  }
  parts.push(`export const abis = {\n${CONTRACTS.map((n) => `  ${n}: ${n}Abi,`).join('\n')}\n} as const;`, '');
  return parts.join('\n');
}
