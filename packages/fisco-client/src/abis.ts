import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const FISCO_CONTRACTS = [
  'MemberRegistry', 'BaseOutbox', 'AgentStatus', 'AssetRegistry', 'SanctionsList', 'JurisdictionRules', 'AttesterRegistry',
  'MandateRegistry', 'AuditLog',
] as const;
export type FiscoContract = (typeof FISCO_CONTRACTS)[number];

export function buildFiscoAbisSource(outDir: string): string {
  const parts = ['// Generated by packages/fisco-client/scripts/gen-abis.ts from contracts/fisco/out. Do not edit by hand.', ''];
  for (const name of FISCO_CONTRACTS) {
    const art = JSON.parse(readFileSync(resolve(outDir, `${name}.sol`, `${name}.json`), 'utf8'));
    parts.push(`export const ${name}Abi = ${JSON.stringify(art.abi, null, 2)} as const;`, '');
    parts.push(`export const ${name}Bytecode = ${JSON.stringify(art.bytecode.object)} as \`0x\${string}\`;`, '');
  }
  parts.push(`export const fiscoAbis = {\n${FISCO_CONTRACTS.map((n) => `  ${n}: ${n}Abi,`).join('\n')}\n} as const;`, '');
  parts.push(`export const fiscoBytecodes = {\n${FISCO_CONTRACTS.map((n) => `  ${n}: ${n}Bytecode,`).join('\n')}\n} as const;`, '');
  return parts.join('\n');
}
