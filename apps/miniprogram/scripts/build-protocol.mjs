// Bundles src/protocol.mjs (+ @noble/hashes keccak) into miniprogram/lib/protocol.js: one CommonJS file, ES2020, no
// dependency left to resolve, so the mini program can `require` it. The output is committed; a test rebuilds it and
// compares, so it never drifts from its source.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = new URL('../miniprogram/lib/protocol.js', import.meta.url);
const BANNER = '// Generated by scripts/build-protocol.mjs from src/protocol.mjs: do not edit. DevTools "ES6 to ES5" must stay off for this file.';

export async function buildProtocol() {
  const r = await build({
    absWorkingDir: root,
    entryPoints: ['src/protocol.mjs'],
    bundle: true,
    format: 'cjs',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    target: 'es2020',
    write: false,
    banner: { js: BANNER },
    legalComments: 'inline',
    logLevel: 'silent',
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await buildProtocol());
  console.log(`wrote ${fileURLToPath(OUT)}`);
}
